"""Write THIRD-PARTY-NOTICES.md from the packages installed in this environment.

    python tools/ci/third_party_notices.py [--output THIRD-PARTY-NOTICES.md]

Run it in the environment the bundle is built from, so the list matches what ships.
The model files are listed from packaging/MODEL_SOURCES.md, kept by hand.
"""
import argparse
import importlib.metadata as metadata
import os
import platform
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SKIP = {'pip', 'setuptools', 'wheel', 'pyinstaller', 'pyinstaller-hooks-contrib',
        'altgraph', 'pefile', 'pywin32-ctypes', 'macholib'}


def licence_of(dist):
    meta = dist.metadata
    expression = meta.get('License-Expression')
    if expression:
        return expression
    classifiers = [c.split('::')[-1].strip() for c in meta.get_all('Classifier') or []
                   if c.startswith('License ::')]
    if classifiers:
        return ', '.join(classifiers)
    text = (meta.get('License') or '').strip().splitlines()
    return text[0][:80] if text else 'see package'


def homepage_of(dist):
    meta = dist.metadata
    if meta.get('Home-page'):
        return meta['Home-page']
    for entry in meta.get_all('Project-URL') or []:
        label, _, url = entry.partition(',')
        if label.strip().lower() in ('homepage', 'home', 'source', 'repository'):
            return url.strip()
    return ''


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', default='THIRD-PARTY-NOTICES.md')
    args = parser.parse_args()
    if os.environ.get('PYTHONPATH'):
        raise SystemExit('PYTHONPATH is set; unset it so only the build environment is listed.')
    rows = {}
    for dist in metadata.distributions():
        name = dist.metadata['Name']
        if name and name.lower() not in SKIP:
            rows[name.lower()] = (name, dist.version, licence_of(dist), homepage_of(dist))
    lines = [
        '# Third-party notices',
        '',
        'FLOD MAS includes the open-source components below. Each remains under its own',
        'licence; the full licence texts ship inside each component\'s folder in the',
        'application bundle. This list is generated by `tools/ci/third_party_notices.py`',
        f'(Python {platform.python_version()}, {platform.system()}); the exact set can',
        'differ slightly between the Windows and the Linux build.',
        '',
        '| Component | Version | Licence | Project |',
        '|---|---|---|---|',
    ]
    for name, version, licence, home in sorted(rows.values(), key=lambda r: r[0].lower()):
        licence = licence.replace('|', '/')
        lines.append(f'| {name} | {version} | {licence} | {home} |')
    lines += ['', 'Python itself is distributed under the Python Software Foundation License.', '']
    sources = ROOT / 'packaging' / 'MODEL_SOURCES.md'
    if sources.is_file():
        lines += [sources.read_text(encoding='utf-8').strip(), '']
    Path(args.output).write_text('\n'.join(lines), encoding='utf-8')
    print(f'wrote {args.output} ({len(rows)} components)')


if __name__ == '__main__':
    main()
